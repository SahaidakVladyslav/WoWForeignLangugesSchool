function ns.GetStrings(langCode)
    return ns.WizardStrings[langCode] or ns.WizardStrings.en
end

function ns.GetLanguageLabel(code)
    for _, l in ipairs(ns.Languages) do
        if l.code == code then return l.label end
    end
    return code
end